-- 4. Storefront validation RPC
CREATE OR REPLACE FUNCTION public.validate_promo_code(p_code text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_code text;
  v_promo record;
BEGIN
  v_code := UPPER(TRIM(COALESCE(p_code, '')));
  IF v_code = '' THEN
    RETURN jsonb_build_object('valid', false, 'message', 'Please enter a promo code.');
  END IF;

  SELECT *
  INTO v_promo
  FROM public.promo_codes
  WHERE UPPER(TRIM(code)) = v_code
  LIMIT 1;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('valid', false, 'message', 'Invalid promo code.');
  END IF;

  IF NOT v_promo.is_active THEN
    RETURN jsonb_build_object('valid', false, 'message', 'This promo code is currently paused.');
  END IF;

  IF v_promo.starts_at IS NOT NULL AND v_promo.starts_at > now() THEN
    RETURN jsonb_build_object('valid', false, 'message', 'This promo code is not active yet.');
  END IF;

  IF v_promo.mode = 'timed' AND (v_promo.expires_at IS NULL OR v_promo.expires_at <= now()) THEN
    RETURN jsonb_build_object('valid', false, 'message', 'This promo code has expired.');
  END IF;

  IF v_promo.max_uses IS NOT NULL AND v_promo.usage_count >= v_promo.max_uses THEN
    RETURN jsonb_build_object('valid', false, 'message', 'This promo code has reached its maximum usage limit.');
  END IF;

  RETURN jsonb_build_object(
    'valid', true,
    'code', v_promo.code,
    'discount_percent', v_promo.discount_percent,
    'mode', v_promo.mode,
    'expires_at', v_promo.expires_at,
    'description', COALESCE(v_promo.description, ''),
    'message', format('%s applied (%s%% off)', v_promo.code, v_promo.discount_percent)
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.validate_promo_code(text) TO authenticated, anon;

-- 5. Atomic redemption RPC on order placement
CREATE OR REPLACE FUNCTION public.redeem_promo_code(p_code text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_code text;
  v_promo record;
BEGIN
  v_code := UPPER(TRIM(COALESCE(p_code, '')));
  IF v_code = '' THEN
    RETURN jsonb_build_object('success', false, 'message', 'No promo code provided.');
  END IF;

  UPDATE public.promo_codes
  SET usage_count = usage_count + 1,
      updated_at = now()
  WHERE UPPER(TRIM(code)) = v_code
    AND is_active = true
    AND (starts_at IS NULL OR starts_at <= now())
    AND (mode = 'manual' OR (expires_at IS NOT NULL AND expires_at > now()))
    AND (max_uses IS NULL OR usage_count < max_uses)
  RETURNING * INTO v_promo;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'message', 'Promo code is inactive, expired, or unavailable.');
  END IF;

  RETURN jsonb_build_object(
    'success', true,
    'code', v_promo.code,
    'discount_percent', v_promo.discount_percent,
    'usage_count', v_promo.usage_count
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.redeem_promo_code(text) TO authenticated;

