-- 1. Create promo_codes table
CREATE TABLE IF NOT EXISTS public.promo_codes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL,
  discount_percent numeric(5, 2) NOT NULL CHECK (discount_percent > 0 AND discount_percent <= 100),
  description text DEFAULT '',
  mode text NOT NULL DEFAULT 'manual' CHECK (mode IN ('manual', 'timed')),
  is_active boolean NOT NULL DEFAULT true,
  starts_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz,
  max_uses integer CHECK (max_uses IS NULL OR max_uses > 0),
  usage_count integer NOT NULL DEFAULT 0 CHECK (usage_count >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT promo_codes_timed_expiry_check CHECK (mode = 'manual' OR expires_at IS NOT NULL)
);

-- Normalize code to uppercase and update updated_at automatically
CREATE OR REPLACE FUNCTION public.normalize_promo_code_fields()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.code := UPPER(TRIM(NEW.code));
  IF char_length(NEW.code) < 3 THEN
    RAISE EXCEPTION 'Promo code must be at least 3 characters long';
  END IF;
  IF NEW.mode = 'manual' THEN
    NEW.expires_at := NULL;
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_normalize_promo_code ON public.promo_codes;
CREATE TRIGGER trg_normalize_promo_code
BEFORE INSERT OR UPDATE ON public.promo_codes
FOR EACH ROW
EXECUTE FUNCTION public.normalize_promo_code_fields();

